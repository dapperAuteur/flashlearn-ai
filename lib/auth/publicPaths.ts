// Which page paths a signed-out visitor may load, and where a sign-in may send
// them afterward. Pure helpers with no Next.js imports, so middleware (edge),
// the sign-in form (browser), and the Jest suite all share one definition.
//
// History: the list used to contain '/' and was tested with
// `pathname.startsWith(path)`. Every pathname starts with '/', so every path
// counted as public and the middleware's sign-in redirect and unverified-email
// gate never ran (production /dashboard answered 200 signed out, 2026-11-06).
// Matching is now exact or segment-prefix: '/blog' covers '/blog' and
// '/blog/x' but not '/blogroll', and '/' covers only the root.
//
// API routes never reach this list: middleware's matcher excludes /api, and
// each API route enforces its own auth (session, API key, or webhook
// signature).

/**
 * Pages a signed-out visitor may load. Each entry matches the exact path and
 * anything below it as a path segment. '/' is special-cased to the root only.
 */
export const PUBLIC_PATHS: readonly string[] = [
  '/',
  // Auth flow. /error, /verified and /verification-error are where the
  // verify-email route and next-auth send a visitor who has no session yet.
  '/auth/signin',
  '/auth/signup',
  '/auth/forgot-password',
  '/auth/reset-password',
  '/error',
  '/verified',
  '/verification-error',
  // A student claiming a teacher-made account has never signed in, so this
  // page has to be reachable with no token.
  '/claim',
  // Marketing and content.
  '/about',
  '/contact',
  '/pricing',
  '/privacy',
  '/terms',
  '/roadmap',
  '/road-map',
  '/changelog',
  '/blog',
  '/press',
  '/help',
  '/docs',
  // Shared and public study surfaces.
  '/explore',
  '/study',
  '/sets',
  '/results',
  '/u',
  '/teams',
  '/versus/how-it-works',
  '/versus/archive',
  '/versus/board',
  '/versus/preview',
  // PWA offline fallback: the service worker serves it when the network is
  // down, and the visitor may have no session cookie at that point.
  '/offline',
  // Files served from public/ or generated by app/robots.ts and app/sitemap.ts.
  '/robots.txt',
  '/sitemap.xml',
  '/manifest.json',
  '/service-worker.js',
  '/images',
  '/.well-known',
];

// Static files the matcher does not already skip (it skips .png and .ico).
// Anything under public/ with one of these extensions must load signed out,
// or the landing page renders with broken images and the PWA cannot install.
const STATIC_FILE = /\.(?:svg|jpe?g|gif|webp|avif|csv|json|js|txt|xml|webmanifest|woff2?|ttf|otf|mp3|mp4|webm|pdf)$/i;

function matchesEntry(pathname: string, entry: string): boolean {
  if (entry === '/') return pathname === '/';
  return pathname === entry || pathname.startsWith(`${entry}/`);
}

/** True when a signed-out visitor may load `pathname` without being sent to sign in. */
export function isPublicPath(pathname: string): boolean {
  if (STATIC_FILE.test(pathname)) return true;
  return PUBLIC_PATHS.some((entry) => matchesEntry(pathname, entry));
}

// Control characters (CR/LF, NUL, tab) can smuggle a newline into a Location
// header, and browsers strip tab/newline from URLs, which turns "/\t/evil" into
// "//evil". Written as escapes so the source stays greppable and lint-clean.
const CONTROL_CHARS = /[\u0000-\u001F\u007F]/;

function localPathOrNull(value: string): string | null {
  if (!value.startsWith('/')) return null;
  // "//host" and "/\host" are read by browsers as another origin.
  if (value.startsWith('//') || value.startsWith('/\\')) return null;
  return value;
}

/**
 * Where to send a visitor after sign-in, given the `callbackUrl` query value.
 *
 * The value is attacker-controlled (`/auth/signin?callbackUrl=https://evil.example`
 * would otherwise turn the sign-in page into an open redirect). Only a
 * same-origin destination survives:
 *   - a path-absolute value ("/dashboard?tab=x") is kept as is;
 *   - an absolute URL is kept only when its origin equals `origin`, and is
 *     reduced to its path, query and hash (next-auth and older links send the
 *     full URL);
 *   - "//host", "/\host", other schemes, control characters, and anything that
 *     points back at the sign-in page fall back to `fallback`.
 */
export function safeCallbackPath(
  raw: string | null | undefined,
  origin: string | null | undefined,
  fallback = '/flashcards',
): string {
  if (typeof raw !== 'string') return fallback;
  const value = raw.trim();
  if (!value || CONTROL_CHARS.test(value)) return fallback;

  let path = localPathOrNull(value);
  if (path === null) {
    if (!origin) return fallback;
    let url: URL;
    try {
      url = new URL(value);
    } catch {
      return fallback;
    }
    if (url.protocol !== 'https:' && url.protocol !== 'http:') return fallback;
    if (url.origin !== origin) return fallback;
    path = localPathOrNull(`${url.pathname}${url.search}${url.hash}`);
    if (path === null) return fallback;
  }

  // Landing back on the sign-in page after signing in looks like a failure.
  if (matchesEntry(path.split(/[?#]/)[0], '/auth/signin')) return fallback;
  return path;
}
